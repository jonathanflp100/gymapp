export function useX(): Strings {
  const { language } = useLanguage();
  return language === 'es-PY' ? es : pt;
}

/** Escolhe o texto do idioma ativo num objeto bilíngue. */
export function useBi() {
  const { language } = useLanguage();
  return (v: { 'pt-BR': string; 'es-PY': string }) => v[language === 'es-PY' ? 'es-PY' : 'pt-BR'];
}
